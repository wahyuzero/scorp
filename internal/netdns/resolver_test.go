func TestIsLoopback(t *testing.T) {
	tests := []struct {
		addr string
		want bool
	}{
		{"127.0.0.1:53", true},
		{"127.0.0.53:53", true},
		{"127.1.2.3:53", true},
		{"[::1]:53", true},
		{"::1", true},
		{"127.0.0.1", true},
		{"localhost:53", true},
		{"localhost", true},
		{"8.8.8.8:53", false},
		{"1.1.1.1:53", false},
		{"9.9.9.9:53", false},
		{"192.168.1.1:53", false},
		{"10.0.0.1:53", false},
	}

	for _, tc := range tests {
		got := IsLoopback(tc.addr)
		if got != tc.want {
			t.Errorf("IsLoopback(%q) = %v; want %v", tc.addr, got, tc.want)
		}
	}
}

func TestParseResolvConf(t *testing.T) {
	sample := `
# Generated by NetworkManager
# Comment line
nameserver 1.1.1.1
nameserver 8.8.8.8:53
nameserver 2001:4860:4860::8888
; Another comment
`
	servers := parseResolvConf(sample)
	if len(servers) != 3 {
		t.Fatalf("expected 3 servers, got %d: %v", len(servers), servers)
	}
	if servers[0] != "1.1.1.1:53" {
		t.Errorf("expected servers[0] == '1.1.1.1:53', got %q", servers[0])
	}
	if servers[1] != "8.8.8.8:53" {
		t.Errorf("expected servers[1] == '8.8.8.8:53', got %q", servers[1])
	}
	if servers[2] != "[2001:4860:4860::8888]:53" {
		t.Errorf("expected servers[2] == '[2001:4860:4860::8888]:53', got %q", servers[2])
	}
}

func TestBuildCandidateList_DeadLoopback(t *testing.T) {
	defer ResetLoopbackProbe()
	SetLoopbackState(false) // simulate Android/Termux without loopback DNS

	list := BuildCandidateList("[::1]:53")
	if len(list) == 0 {
		t.Fatal("candidate list must not be empty")
	}

	// First server should NOT be [::1]:53
	if list[0] == "[::1]:53" || list[0] == "127.0.0.1:53" {
		t.Errorf("dead loopback must not be prioritized, got first candidate: %s", list[0])
	}

	// Should contain standard fallbacks
	hasCloudflare := false
	hasGoogle := false
	for _, s := range list {
		if s == "1.1.1.1:53" {
			hasCloudflare = true
		}
		if s == "8.8.8.8:53" {
			hasGoogle = true
		}
	}
	if !hasCloudflare || !hasGoogle {
		t.Errorf("candidate list should contain public fallbacks, got: %v", list)
	}
}

