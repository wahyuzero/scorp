func TestResilientResolver_LookupSuccess(t *testing.T) {
	// Verify that the resilient resolver successfully resolves hosts even if
	// loopback is dead (reproducing Android/Termux environment)
	defer ResetLoopbackProbe()
	SetLoopbackState(false)

	resolver := GetResolver()
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()

	ips, err := resolver.LookupHost(ctx, "api.commandcode.ai")
	if err != nil {
		t.Fatalf("resilient lookup for api.commandcode.ai failed: %v", err)
	}
	if len(ips) == 0 {
		t.Fatal("expected at least one IP address returned")
	}
	for _, ip := range ips {
		if parsed := net.ParseIP(ip); parsed == nil {
			t.Errorf("invalid IP returned: %s", ip)
		}
	}
}

func TestResilientDNSConn_FailoverSimulation(t *testing.T) {
	// Create a ResilientDNSConn with an initial unreachable loopback conn,
	// and verify it transparently fails over to 1.1.1.1:53
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()

	dialer := &net.Dialer{Timeout: 2 * time.Second}
	deadConn, err := dialer.DialContext(ctx, "udp", "127.0.0.1:53")
	if err != nil {
		t.Skip("skipping UDP dial simulation: OS refused initial UDP connect")
	}

	conn := &ResilientDNSConn{
		Conn:          deadConn,
		ctx:           ctx,
		network:       "udp",
		dialer:        dialer,
		fallbackAddrs: []string{"1.1.1.1:53", "8.8.8.8:53"},
	}
	defer conn.Close()

	_ = conn.SetDeadline(time.Now().Add(3 * time.Second))

	// DNS query for example.com A record
	query := []byte{
		0xaa, 0xbb, 0x01, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x07, 0x65, 0x78, 0x61, 0x6d, 0x70, 0x6c, 0x65, 0x03, 0x63, 0x6f, 0x6d, 0x00, 0x00, 0x01, 0x00, 0x01,
	}

	_, err = conn.Write(query)
	if err != nil {
		t.Fatalf("conn.Write failed: %v", err)
	}

	buf := make([]byte, 512)
	n, err := conn.Read(buf)
	if err != nil {
		t.Fatalf("conn.Read failover failed: %v", err)
	}
	if n < 12 {
		t.Fatalf("DNS response too short: %d bytes", n)
	}
}
